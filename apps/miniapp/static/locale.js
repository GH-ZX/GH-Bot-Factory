export function localizeStatic(){
  const walker=document.createTreeWalker(document.body,NodeFilter.SHOW_TEXT);
  while(walker.nextNode()){
    const node=walker.currentNode, key=node.textContent.trim();
    if(ar[key] && !node.parentElement.closest('script,style'))nodes.push({node,key});
  }
  document.querySelectorAll('[placeholder],[aria-label]').forEach(node=>{
    for(const attr of ['placeholder','aria-label']){const key=node.getAttribute(attr);if(ar[key])nodes.push({node,key,attr});}
  });
}
export function setLanguage(preferred,tenantId,save=false){
  let selected=preferred==='ar'?'ar':'en';
  try{const key=`ghbf_language:${tenantId}`;if(save)sessionStorage.setItem(key,selected);else selected=sessionStorage.getItem(key)||selected;}catch(_){}
  language=selected==='ar'?'ar':'en';
  document.documentElement.lang=language;document.documentElement.dir=language==='ar'?'rtl':'ltr';
  document.getElementById('storeLanguage').value=language;
  for(const item of nodes){if(item.attr)item.node.setAttribute(item.attr,t(item.key));else item.node.textContent=t(item.key);}
}

